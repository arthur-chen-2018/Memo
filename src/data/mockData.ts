// Helper: get memos for a specific work order
export function getMemosForWorkOrder(workOrderNumber: string): Memo[] {
  return memos.filter(m => m.workOrderNumber === workOrderNumber);
}

// Helper: count open memos on a work order
export function getOpenMemoCount(workOrderNumber: string): number {
  return memos.filter(
    m => m.workOrderNumber === workOrderNumber && m.status !== 'Closed'
  ).length;
}

// Helper: get messages for a memo
export function getMessagesForMemo(memoId: string): Message[] {
  return messages.filter(m => m.memoId === memoId);
}

// Helper: get attachments for a memo
export function getAttachmentsForMemo(memoId: string): Attachment[] {
  return attachments.filter(a => a.memoId === memoId);
}

// Helper: get activity log for a memo
export function getActivityLogForMemo(memoId: string): ActivityLogEntry[] {
  return activityLog.filter(a => a.memoId === memoId);
}
